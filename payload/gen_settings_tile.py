#!/usr/bin/env python3
"""Embed checked-in tile assets; no image library, network or runtime file needed."""
import json
import struct
from pathlib import Path
ROOT = Path(__file__).resolve().parent
icon = (ROOT / 'settings-tile/icon0.png').read_bytes()
param = (ROOT / 'settings-tile/param.json').read_bytes()
meta = json.loads(param)
assert meta['titleId'] == 'SCPS50001'
assert meta['deeplinkUri'] == 'http://127.0.0.1:8090/'
assert meta['applicationCategoryType'] == 65536
assert icon[:8] == b'\x89PNG\r\n\x1a\n' and struct.unpack('>II', icon[16:24]) == (512, 512)
assert len(icon) <= 1024 * 1024 and len(param) <= 8192
out = '/* Generated by gen_settings_tile.py; do not commit. */\n'
for name, data in [('settings_icon', icon), ('settings_param', param)]:
    out += f'static const unsigned char {name}[] = {{\n'
    out += ''.join('  ' + ','.join(str(b) for b in data[i:i+24]) + ',\n' for i in range(0, len(data), 24))
    out += '};\n'
(ROOT / 'settings_tile_assets.h').write_text(out, encoding='ascii')
